import fs from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadCityIndex } from "./gazetteer/query.mjs";
import { cityDefinitions, regionDefinitions, siteDefinitions, citySourceIds, citiesWithoutCoordinates } from "./place-definitions.mjs";
import { extraPlaces } from "./location-overrides.mjs";

export function createPlaceCatalog(index = loadCityIndex()) {
  const cities = cityDefinitions.map(([slug, title, query, country, modernName, aliases]) => {
    const id = "city-" + slug;
    const candidates = index.find(query, { country });
    const pinned = citySourceIds[slug];
    // Pinned IDs are looked up by source identity, including alternate names.
    const city = citiesWithoutCoordinates.has(slug) ? null : pinned
      ? index.get(pinned)
      : candidates.length === 1 ? candidates[0] : null;
    if ((!city || city.country !== country) && !citiesWithoutCoordinates.has(slug))
      throw new Error(`City needs an unambiguous source identity: ${slug} (${query}, ${pinned || candidates.length})`);
    return { id, title, aliases, location: {
      id, kind: "point", modernName,
      variants: city ? [{ id: "city-reference", name: title,
        coordinates: [city.lon, city.lat],
        accuracy: "现代聚落位置参照；不代表古城、宫殿或战场的精确位置。",
        source: { title: `GeoNames · ${city.name} · ${city.id}`, url: `https://www.geonames.org/${city.id}/` },
      }] : [],
    } };
  });
  const regions = (definitions, prefix) => definitions.map(([slug, title, modernName, aliases]) => ({
    id: prefix + slug, title, aliases,
    location: { id: prefix + slug, kind: "region", modernName, variants: [] },
  }));
  return [...cities, ...regions(regionDefinitions, "region-"), ...regions(siteDefinitions, "site-"), ...extraPlaces];
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const places = createPlaceCatalog();
  const target = fileURLToPath(new URL("../../.vitepress/vault/geo-places.mjs", import.meta.url));
  const content = "// Generated by scripts/geo/build-place-catalog.mjs.\n" +
    "// Human-reviewed identities: scripts/geo/place-definitions.mjs.\n" +
    "// GeoNames coordinates: CC BY 4.0; see public/geo/sources/geonames/SOURCES.md.\n" +
    "export const geographicPlaces = " + JSON.stringify(places, null, 2) + ";\n";
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(target, "utf8") !== content) throw new Error("Place catalog is out of date");
  } else {
    // Read before replacing an existing generated catalog.
    if (fs.existsSync(target)) fs.readFileSync(target, "utf8");
    fs.writeFileSync(target, content);
  }
  console.log(`${places.length} geographic records; ${places.filter((p) => p.location.variants.length).length} city coordinates`);
}
